import assert from 'node:assert/strict'
import { join } from 'node:path'

export async function checkTodayAndOrder(page, output) {
  await page.evaluate(async () => { await window.configure({ sidebarTodayMetric: 'cost' }); window.remount() })
  await page.getByRole('tab', { name: '显示', exact: true }).click()
  const target = key => page.locator('.cm-preview .cm-sidebar-target[data-cm-order-key="' + key + '"]')
  await target('today').click()
  await page.locator('input[data-display-option=today-tokens]').check()
  await page.waitForFunction(() => window.current().sidebarTodayMetric === 'both' && document.querySelectorAll('#actual-sidebar [data-cm-today]').length === 2)
  const actual = page.locator('#actual-sidebar [data-cm-display=today]')
  assert.equal(await actual.locator('[data-cm-today]').count(), 2)
  for (const part of ['today-cost', 'today-tokens']) assert.equal(await page.locator('.cm-preview .cm-sidebar-target[data-display-part="' + part + '"]').count(), 1)
  for (const width of [352, 280]) {
    await page.locator('#actual-sidebar').evaluate((node, width) => { node.style.width = width + 'px' }, width)
    assert.ok(await actual.evaluate(node => {
      const outer=node.getBoundingClientRect()
      return [...node.querySelectorAll('[data-cm-today]')].every(child => { const box=child.getBoundingClientRect();return box.right <= outer.right + 1 && box.left >= outer.left - 1 })
    }), 'today cost and tokens fit the sidebar')
  }
  await page.locator('#actual-sidebar').evaluate(node => { node.style.width = '352px' })
  await page.screenshot({ path: join(output, 'today-both-and-subitems.png'), fullPage: true })
  await page.locator('input[data-display-option=today-cost]').uncheck()
  await page.waitForFunction(() => window.current().sidebarTodayMetric === 'tokens' && !document.querySelector('#actual-sidebar [data-cm-today=cost]'))
  assert.equal(await actual.locator('[data-cm-today=cost]').count(), 0)
  await page.locator('input[data-display-option=today-cost]').check()
  await page.locator('input[data-display-option=today-tokens]').uncheck()
  await page.waitForFunction(() => window.current().sidebarTodayMetric === 'cost' && !document.querySelector('#actual-sidebar [data-cm-today=tokens]'))

  await target('today').dragTo(target('balance'), { targetPosition: { x: 10, y: 2 } })
  await page.waitForFunction(() => window.current().sidebarOrder.indexOf('today') >= 0 && window.current().sidebarOrder.indexOf('today') < window.current().sidebarOrder.indexOf('balance'))
  await page.locator('#actual-sidebar').evaluate(node => { node.style.position='static';node.style.left='auto' })
  assert.equal(await page.locator('#actual-sidebar .cm-order-handle,#actual-sidebar .cm-order-status,#actual-sidebar [draggable=true]').count(), 0, 'live sidebar has no reorder widgets or injected status')
  await target('balance').focus(); await target('balance').press('ArrowUp')
  await page.waitForFunction(() => window.current().sidebarOrder.indexOf('balance') < window.current().sidebarOrder.indexOf('today'))
  const before = await page.evaluate(() => window.current().sidebarOrder)
  await page.evaluate(() => { window.failSave = true })
  await target('balance').press('ArrowDown')
  await page.locator('.cm-tabs-row .cm-msg.err').waitFor()
  assert.deepEqual(await page.evaluate(() => window.current().sidebarOrder), before, 'failed sidebar save keeps the previous order')
  await page.evaluate(() => { window.failSave = false })
  await target('today').click()
  await page.locator('input[data-display-option=today-tokens]').check()
  await page.waitForFunction(() => window.current().sidebarTodayMetric === 'both' && window.current().sidebarOrder.indexOf('today') < window.current().sidebarOrder.indexOf('balance'))
  await page.locator('[data-display-toggle=today]').click()
  await page.waitForFunction(() => window.current().sidebar === false)
  await page.locator('[data-display-toggle=today]').click()
  await page.waitForFunction(() => window.current().sidebar === true)
  await page.getByRole('checkbox', { name: '使用示例数据', exact: true }).uncheck()
  await page.evaluate(async () => {
    window.setFixtureState({ gatewayQuotas: [{ id: 'fixture-one', status: 'ok', accounts: [{ id: 'a', provider: 'codex', label: 'Test account', status: 'ok', windows: [] }] }] })
    await window.configure({ gatewayQuotas: { sources: [{ id: 'fixture-one', type: 'cliproxyapi', label: 'Test gateway', baseURL: 'https://example.invalid', enabled: true, display: 'sidebar', refreshMinutes: 5, includeProviders: ['codex'], allowedHosts: ['example.invalid'], allowInsecureHttp: false }] } })
    window.remount()
  })
  await page.getByRole('tab', { name: '显示', exact: true }).click()
  await target('gateway:fixture-one').dragTo(target('today'), { targetPosition: { x: 10, y: 2 } })
  await page.waitForFunction(() => window.current().sidebarOrder.includes('gateway:fixture-one') && !window.current().sidebarOrder.includes('gateway'))
  assert.equal(await page.locator('.cm-tabs-row .cm-msg.err').count(), 0, 'gateway reorder uses its stable source ID and saves')
  await page.getByRole('checkbox', { name: '使用示例数据', exact: true }).check()
  await page.screenshot({ path: join(output, 'sidebar-settings-order.png'), fullPage: true })
  await page.evaluate(async () => {
    const patch={sidebarOrder:[],sidebarTodayMetric:'cost',gatewayQuotas:{sources:[]}}
    await window.saveConfig(patch);window.setConfig(patch);window.remount()
  })
  await page.getByRole('tab', { name: '显示', exact: true }).click()
  await page.locator('.cm-display').waitFor()
  await page.locator('#actual-sidebar').evaluate(node => { node.style.position='fixed';node.style.left='-2000px' })
}
